/**
 * Russian typography: non-breaking spaces after one- and two-letter prepositions/conjunctions
 * and between a number and its unit, so lines never end with «в», «по», «от» or split «40 ₪».
 */
const NB = '\u00A0';
function typo<T>(v: T): T {
  if (typeof v === 'string') {
    return v
      .replace(/(^|[\s(«—])(в|во|на|по|до|от|из|за|к|ко|с|со|у|о|об|и|а|но|не|для|без|при|под|над|что|как)\s+/gi, `$1$2${NB}`)
      .replace(/(^|[\s(«—])(в|во|на|по|до|от|из|за|к|ко|с|со|у|о|об|и|а|но|не|для|без|при|под|над|что|как)\s+/gi, `$1$2${NB}`)
      .replace(/(\d)\s+(₪|г\b|кг|мг|мм|см|м\b|л\b|ч\b|%|шт|рабочих|дней|товар|°C|минут)/g, `$1${NB}$2`)
      .replace(/\s+—/g, `${NB}—`) as T;
  }
  if (Array.isArray(v)) return v.map(typo) as T;
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, k === 'lang' || k === 'dir' ? x : typo(x)])) as T;
  return v;
}

